-- Paya Music UG: count song downloads.
-- Run this once in Supabase SQL Editor.
create table if not exists public.song_downloads (
  id bigint generated by default as identity primary key,
  song_id bigint not null references public.songs(id) on delete cascade,
  downloaded_at timestamptz not null default now()
);

create index if not exists song_downloads_song_id_idx
  on public.song_downloads(song_id);

create index if not exists song_downloads_downloaded_at_idx
  on public.song_downloads(downloaded_at);

-- Writes are performed by the server using the Supabase service role.
alter table public.song_downloads enable row level security;
