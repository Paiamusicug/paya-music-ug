-- Paya Music UG: play-count tracking for the Most Played chart.
-- Run this once in Supabase SQL Editor.
create table if not exists public.song_plays (
  id bigint generated by default as identity primary key,
  song_id bigint not null references public.songs(id) on delete cascade,
  played_at timestamptz not null default now()
);

create index if not exists song_plays_song_id_idx
  on public.song_plays(song_id);

create index if not exists song_plays_played_at_idx
  on public.song_plays(played_at);

-- The app writes through the server-side Supabase service role.
alter table public.song_plays enable row level security;
