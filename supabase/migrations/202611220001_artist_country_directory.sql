CREATE TABLE IF NOT EXISTS public.artist_countries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artist_name text NOT NULL,
  normalized_name text NOT NULL UNIQUE,
  country text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS artist_countries_country_idx
  ON public.artist_countries (lower(country));

ALTER TABLE public.artist_countries ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read artist countries" ON public.artist_countries;
CREATE POLICY "Public can read artist countries"
  ON public.artist_countries FOR SELECT
  USING (true);

