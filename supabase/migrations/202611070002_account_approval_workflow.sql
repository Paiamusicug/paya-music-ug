-- Account persistence defaults and moderation queue for artist profile changes.
ALTER TABLE public.users ALTER COLUMN created_at SET DEFAULT now();
ALTER TABLE public.users ALTER COLUMN bio SET DEFAULT '';

CREATE TABLE IF NOT EXISTS public.profile_submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  name text NOT NULL,
  bio text NOT NULL DEFAULT '',
  avatar_url text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  reviewed_by bigint,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS profile_submissions_pending_created_idx
  ON public.profile_submissions (created_at) WHERE status = 'pending';

-- Existing published stories remain published; newly submitted stories are pending.
ALTER TABLE public.news ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'published';
