-- Paya Music UG revenue request system
-- Run this once in Supabase SQL Editor.
create table if not exists public.revenue_requests (
  id bigint generated by default as identity primary key,
  service_type text not null check (service_type in ('advertising','featured_artist','music_promotion','sponsored_news')),
  customer_name text not null,
  contact_email text not null,
  contact_whatsapp text,
  details text,
  status text not null default 'new' check (status in ('new','contacted','paid','completed','rejected')),
  amount_agreed numeric(12,2),
  payment_reference text,
  owner_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.revenue_requests enable row level security;
revoke all on table public.revenue_requests from anon, authenticated;
