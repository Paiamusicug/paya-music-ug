-- Paya Music UG: owner approval queue for submitted profile changes.
-- Run once in the Supabase SQL Editor. Existing accounts and Owner role are untouched.
create table if not exists public.content_submissions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  submission_type text not null check (submission_type in ('profile')),
  payload jsonb not null default '{}'::jsonb,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  review_note text,
  reviewed_at timestamptz,
  reviewed_by bigint references public.users(id),
  created_at timestamptz not null default now()
);
create index if not exists content_submissions_pending_created_idx
  on public.content_submissions (status, created_at);
